"""Виправлення тексту листа — одне місце для обох боків.

Правку роблять двома шляхами: автор через маршрут `PATCH /messages/{id}`,
співрозмовник — кадром `edit` через приймальню. Дія над рядком у них ОДНА, і
жити вона мусить в одному місці: дві копії однієї угоди в різних файлах цього
дому вже розходились тричі.

Ключове рішення протоколу: по дроту їде **ціле нове тіло**, а не різниця.
Кадр може приїхати вдруге — смуга повторів везе його, поки не дістане
підтвердження, — і застосування різниці подвоїло б правку. Ціле тіло
ідемпотентне за побудовою: скільки разів не приклади, результат той самий.
"""
from __future__ import annotations

from datetime import datetime, timezone

from db.models import MessengerMessage
from messenger.crypto.at_rest import seal
from messenger.crypto.keys import KeyStore

#: Стеля тексту. Та сама, що на надсиланні: правкою не можна пронести більше,
#: ніж пропустив би звичайний лист.
EDIT_MAX_CHARS = 8000


def _now() -> datetime:
    return datetime.now(timezone.utc).replace(tzinfo=None)


def apply_edit(keys: KeyStore, row: MessengerMessage, body: str) -> None:
    """Кладе нове тіло в рядок і позначає час правки.

    Тіло запечатують тим самим ключем вузла, що й при надсиланні: інакше
    виправлений лист лежав би відкритим там, де вихідний лежить закритим, і
    правка тихо знижувала б захист.

    Відкритий `body` затирається навмисно. У старих рядках він ще трапляється,
    і якби ми лишили його як є, `_body_of` віддав би СТАРИЙ текст: він читає
    відкрите поле, лише коли немає запечатаного, але порядок тут зворотний —
    запечатане з'явилось, а відкрите лишилось би від попередньої версії.
    """
    row.ciphertext = seal(keys, body, aad=row.id.encode()).hex()
    row.body = None
    row.edited_at = _now()
