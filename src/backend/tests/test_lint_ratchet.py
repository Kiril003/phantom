"""Стеля лінту, яка тільки падає. Замість базової лінії.

Чому НЕ базова лінія. Дім 30.08.2026 виміряв, що лінтер не бігав у трьох
деревах із трьох: у ПК не було конфіга при живому скрипті, у месенджера те
саме, у телефона конфіг був ретельний — і виклику не існувало. Спокуса
після такого одна: увімкнути інструмент і дозволити йому створити базову
лінію з поточного боргу. Штаб це відхилив, і аргумент точний:

    базова лінія робить те саме, що мовчазний лінтер, просто повільніше —
    ховає конкретні місця під одним файлом, який ніхто не перечитує.

Ratchet тримає борг **видимим і поіменним**: число на очах, воно може лише
зменшуватись, і нове зауваження одразу штовхає його вгору — тобто червоніє.

ЧОГО ЦЕЙ СТОРОЖ НЕ БАЧИТЬ ЗА ПОБУДОВОЮ — читати перед тим, як вірити:
* Він рахує ШТУКИ, а не вагу. Прибрати десять `react-refresh` попереджень і
  додати одну справжню помилку — для нього поліпшення. Тому окремі стелі
  для помилок і попереджень, а не одна сума.
* Він не знає, чи правила правильні. Вимкнене правило не рахується взагалі;
  послаблення `error` → `warn` виглядатиме як прогрес по помилках.
* Він нічого не каже про те, чи лінт бігає у ВОРОТАХ. Сторож у тестах і
  крок у `gate.sh` — різні речі; другого поки немає, і це чесно сказано.
"""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

import pytest

FRONTEND = Path(__file__).resolve().parents[2] / "frontend"

# Виміряно 30.08.2026 командою нижче. Ці числа мають ТІЛЬКИ ПАДАТИ.
# 28 -> 20: закрито вісім `no-empty`. Шість у `storagePersistence.ts`
# тепер називають відмову сховища словом (читання й далі повертає
# запасне значення — міняється не поведінка, а чутність); два в
# `aiEngineService.ts` виявились ЧЕСНИМИ й лишились порожніми з
# поясненням: там розбір формату, а виняток однаково летить далі.
# Піднімати їх можна лише свідомим рішенням із поясненням у цьому файлі —
# і тоді це вже не ratchet, а нова база, тож пояснення обов'язкове.
# 107 -> 94: закрито всі 13 `react-hooks/exhaustive-deps` (30.08, рішенням на
# кожне, не `--fix`) плюс знято один власний глушник, який виявився зайвим.
#
# Що показало це вимірювання і чого стеля НЕ бачить: із 94 попереджень **75 —
# це мертві `eslint-disable`**, тобто коментарі, які глушать правило, що й так
# мовчить. Вони рахуються нарівні зі справжніми зауваженнями, тож 80% «боргу
# попереджень» тут — не код, а стара тиша про неіснуючі проблеми. Знімаються
# механічно (`npx eslint . --fix --fix-type directive`), але зачіпають файли
# чужих фронтів, тож це окреме узгоджене рішення, а не побічна правка.
#
# 94 -> 19 і 20 -> 1 (03.09): ті самі 75 мертвих `eslint-disable` таки знято
# (94 − 75 = 19 рівно), і помилок лишилась одна. Стелю опускаю НЕ як рішення
# про новий борг, а тому що ratchet сам почервонів: запас між правдою і
# стелею був 19 і 75, тобто в нього тихо вмістилося б стільки ж нового.
CEILING_ERRORS = 1
CEILING_WARNINGS = 19


def _lint() -> tuple[int, int, list[str]]:
    npx = shutil.which("npx")
    if npx is None or not (FRONTEND / "node_modules").is_dir():
        pytest.skip("немає npx або node_modules — лінт тут не запустити")

    proc = subprocess.run(
        [npx, "eslint", ".", "-f", "json"],
        cwd=FRONTEND,
        capture_output=True,
        text=True,
        timeout=900,
    )
    # ESLint віддає ненульовий код, коли є помилки — це нормально, нас
    # цікавить звіт, а не код виходу. Порожній stdout — інша річ: значить
    # він не побіг, і мовчати про це не можна.
    payload = proc.stdout.strip()
    if not payload:
        pytest.fail(
            "eslint не дав звіту — найімовірніше не запустився зовсім.\n"
            f"stderr: {proc.stderr[:400]}"
        )
    data = json.loads(payload)
    errors = sum(f["errorCount"] for f in data)
    warnings = sum(f["warningCount"] for f in data)
    worst = [
        f"{Path(f['filePath']).name}: {m.get('ruleId')} — {m['message'][:60]}"
        for f in data
        for m in f["messages"]
        if m["severity"] == 2
    ]
    return errors, warnings, worst


def test_lint_errors_do_not_grow():
    errors, _, worst = _lint()
    assert errors <= CEILING_ERRORS, (
        f"помилок лінту {errors}, стеля {CEILING_ERRORS} — борг виріс.\n"
        "Стелю не піднімають, щоб пройти: або лікуй, або визнай рішенням.\n"
        + "\n".join(f"  • {w}" for w in worst[:10])
    )


def test_lint_warnings_do_not_grow():
    _, warnings, _ = _lint()
    assert warnings <= CEILING_WARNINGS, (
        f"попереджень лінту {warnings}, стеля {CEILING_WARNINGS} — борг виріс."
    )


def test_ceiling_is_not_stale():
    """Якщо борг упав помітно нижче стелі — стелю час опустити.

    Інакше ratchet перестає бути ratchet: між реальним числом і стелею
    накопичується запас, у який можна тихо додавати нове.
    """
    errors, warnings, _ = _lint()
    slack_e = CEILING_ERRORS - errors
    slack_w = CEILING_WARNINGS - warnings
    assert slack_e <= 5 and slack_w <= 15, (
        f"стеля відстала від правди: помилки {errors}/{CEILING_ERRORS} "
        f"(запас {slack_e}), попередження {warnings}/{CEILING_WARNINGS} "
        f"(запас {slack_w}). Опусти стелю до поточних чисел — інакше в цей "
        "запас непомітно вміститься нове."
    )
