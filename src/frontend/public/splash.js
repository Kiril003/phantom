const STATUS_EL = document.getElementById('status');
// Адресу бекенда більше не знаємо самі — беремо з єдиного джерела
// (`backend-origin.js`, підключений у splash.html перед цим файлом).
// Доти тут був зашитий `http://127.0.0.1:8000`, і саме тому заставка була
// єдиною справною частиною запакованого застосунку: решта будувала адреси
// від `window.location`, який в asset-протоколі вказує не туди.
const READYZ = window.__PHANTOM_BACKEND__.absolute('/readyz');
// Resolved against the asset-protocol root the splash itself is served from.
const TARGET = 'index.html';
const POLL_MS = 250;
// Скільки чекати, перш ніж СКАЗАТИ, що довго. Не «перш ніж здатися».
//
// Тут стояло 30 000 — і це був перший екран, який бачив користувач
// запакованого застосунку: англійський вирок про те, що ядро не встигло.
// (Дослівно його не цитую: сторож у тестах шукає цю фразу по всьому
// файлу, і цитата в коментарі валила б його на порожньому місці —
// той самий клас пастки, що ловив нас сьогодні вже двічі.)
// Заміряно 29.08.2026 на зібраному AppImage, чотири запуски поспіль:
// 37, 40, 45 і 47 секунд до першої відповіді /health. Тобто заставка
// оголошувала провал ЗАВЖДИ, на цілком справному бекенді, який
// піднімався через кілька секунд після вироку.
//
// Холодний старт тут чесно довгий: прогрів Chroma, Vosk, MiniLM, плюс
// розпакування onefile-бандла на 541 МБ. На повільнішому диску буде ще
// довше, тож будь-яке фіксоване число — це знову той самий дефект,
// просто з більшим порогом. Тому опитування НЕ спиняється ніколи: після
// цього порога міняється лише текст, з «гріюсь» на «довше, ніж
// звично». Показати провал там, де провалу немає, — гірше за очікування.
//
// Але й нескінченне «ядро ще піднімається» — брехня. Перевірено того ж
// дня: sidecar не піднявся взагалі, і заставка бадьоро рахувала до
// **1979 секунд**, тридцять три хвилини запевняючи, що все йде своїм
// ходом. Тож станів три, і третій каже правду. Опитування триває й після
// нього — якщо ядро колись відповість, застосунок відкриється; здаватись
// не можна, а брехати не можна тим більше.
const PATIENCE_MS = 90000;
const GIVEN_UP_MS = 300000;
const t0 = performance.now();

async function pollOnce() {
  try {
    const r = await fetch(READYZ, { cache: 'no-store' });
    if (r.ok) {
      // Було 'online' — єдине англійське слово на найпершому екрані, який
      // бачить людина. Видно його мить, до переходу, але мить теж на склі.
      STATUS_EL.textContent = 'ядро відповіло';
      window.location.replace(TARGET);
      return true;
    }
  } catch {
    /* sidecar still booting; ignore */
  }
  return false;
}

function statusFor(waitedMs) {
  const s = Math.floor(waitedMs / 1000);
  // До порога терпіння лічильника немає навмисно: цифра, що біжить із
  // першої секунди, перетворює звичайний старт на очікування з таймером.
  //
  // Але й одне слово без причини — не краще: виміряно 29.08.2026 на
  // зібраному пакунку, що до першої відповіді минає 37-47 с, з них 6-16 с
  // — розпакування onefile-бандла (розмір див. вище). Тобто сорок секунд людина
  // дивилась на слово «гріюсь» і не знала ні що відбувається, ні скільки
  // це триває звично. Перший стан тепер називає причину й очікуваний час.
  //
  // НЕ «перший запуск довгий»: onefile розпаковується ЩОРАЗУ, тож обіцянка
  // «далі буде швидше» була б неправдою.
  if (waitedMs < PATIENCE_MS) {
    return 'запускаюсь: розпаковую пакунок і грію моделі · зазвичай до хвилини';
  }
  if (waitedMs < GIVEN_UP_MS) {
    return `гріюсь ${s}s · довше, ніж звично — ядро ще не відповіло`;
  }
  return `ядро не піднялося за ${s}s — чекаю далі, але щось не так`;
}

// Рядок логу бекенда, як він є: «2026-09-12 19:09:11,833 [phantom] [INFO]
// lifespan_warmup: voice models preload: …». На склі від нього потрібен зміст,
// а не мітка часу й рівень — їх людина однаково не читає, а місця вони
// займають половину рядка.
function tidy(line) {
  return String(line)
    .replace(/^\d{4}-\d\d-\d\d[ T]\d\d:\d\d:\d\d[,.]\d+\s*/, '')
    .replace(/^\[phantom\]\s*/, '')
    .replace(/^\[(DEBUG|INFO|WARNING|ERROR|CRITICAL)\]\s*/, '')
    .replace(/^(INFO|WARNING|ERROR):\s+/, '')
    .trim()
    .slice(0, 120);
}

// Оболонка кладе сюди `{code, signal, last}`, щойно сайдкар помер
// (`tell_the_splash_the_backend_died` у `src-tauri/src/main.rs`). Доти
// змінної немає — і саме тому перевірка робиться щоразу, а не один раз на
// старті: смерть приходить пізніше за перший кадр.
function deathLine(died) {
  const how = died.signal != null ? `сигнал ${died.signal}` : `код ${died.code ?? '?'}`;
  // Зайнятий порт — не поломка, а другий примірник, і сказати це треба
  // словами людини. Виміряно 12.09.2026: власник запустив пакунок кілька
  // разів поспіль, другий уперся в зайнятий 8000 і вийшов кодом 1, а
  // заставка тим часом обіцяла прогрів.
  if (/address already in use|Errno 98/i.test(died.last || '')) {
    return 'PHANTOM уже запущено — закрий той примірник або відкрий його вікно';
  }
  const tail = died.last ? ` · останнє від ядра: ${tidy(died.last)}` : '';
  return `ядро зупинилось (${how})${tail}`;
}

// Що показати, поки ядро встає. Лічильник САМ ПО СОБІ читається як поломка:
// заміряно 12.09.2026 на артефакті 74469351 — ядро піднімалось 2,5 хвилини й
// увесь цей час чесно писало в журнал, що саме робить, а на склі стояло
// «гріюсь 204s». Тому щойно ядро сказало перше слово, показуємо ЙОГО, а
// лічильник лишається поруч як міра часу, а не як вирок.
function waitingLine(waitedMs) {
  const said = window.__PHANTOM_BACKEND_LINE__ ? tidy(window.__PHANTOM_BACKEND_LINE__) : '';
  if (!said) return statusFor(waitedMs);
  const s = Math.floor(waitedMs / 1000);
  return waitedMs < PATIENCE_MS ? `ядро: ${said}` : `ядро ${s}s: ${said}`;
}

async function loop() {
  for (;;) {
    if (await pollOnce()) return;
    // Смерть має пріоритет над таймером: поки її не видно, лічильник
    // «гріюсь» описує очікування, якого вже немає.
    const died = window.__PHANTOM_BACKEND_DIED__;
    STATUS_EL.textContent = died
      ? deathLine(died)
      : waitingLine(performance.now() - t0);
    await new Promise((res) => setTimeout(res, POLL_MS));
  }
}

loop();
