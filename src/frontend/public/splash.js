const STATUS_EL = document.getElementById('status');
// Адресу бекенда більше не знаємо самі — беремо з єдиного джерела
// (`backend-origin.js`, підключений у splash.html перед цим файлом).
// Доти тут був зашитий `http://127.0.0.1:8000`, і саме тому заставка була
// єдиною справною частиною запакованого застосунку: решта будувала адреси
// від `window.location`, який в asset-протоколі вказує не туди.
const READYZ = window.__PHANTOM_BACKEND__.absolute('/readyz');
// Resolved against the asset-protocol root the splash itself is served from.
const TARGET = 'index.html';
const POLL_MS = 250;
// Скільки чекати, перш ніж СКАЗАТИ, що довго. Не «перш ніж здатися».
//
// Тут стояло 30 000 — і це був перший екран, який бачив користувач
// запакованого застосунку: англійський вирок про те, що ядро не встигло.
// (Дослівно його не цитую: сторож у тестах шукає цю фразу по всьому
// файлу, і цитата в коментарі валила б його на порожньому місці —
// той самий клас пастки, що ловив нас сьогодні вже двічі.)
// Заміряно 29.08.2026 на зібраному AppImage, чотири запуски поспіль:
// 37, 40, 45 і 47 секунд до першої відповіді /health. Тобто заставка
// оголошувала провал ЗАВЖДИ, на цілком справному бекенді, який
// піднімався через кілька секунд після вироку.
//
// Холодний старт тут чесно довгий: прогрів Chroma, Vosk, MiniLM, плюс
// розпакування onefile-бандла на 541 МБ. На повільнішому диску буде ще
// довше, тож будь-яке фіксоване число — це знову той самий дефект,
// просто з більшим порогом. Тому опитування НЕ спиняється ніколи: після
// цього порога міняється лише текст, з «гріюсь» на «довше, ніж
// звично». Показати провал там, де провалу немає, — гірше за очікування.
//
// Але й нескінченне «ядро ще піднімається» — брехня. Перевірено того ж
// дня: sidecar не піднявся взагалі, і заставка бадьоро рахувала до
// **1979 секунд**, тридцять три хвилини запевняючи, що все йде своїм
// ходом. Тож станів три, і третій каже правду. Опитування триває й після
// нього — якщо ядро колись відповість, застосунок відкриється; здаватись
// не можна, а брехати не можна тим більше.
const PATIENCE_MS = 90000;
const GIVEN_UP_MS = 300000;
const t0 = performance.now();

async function pollOnce() {
  try {
    const r = await fetch(READYZ, { cache: 'no-store' });
    if (r.ok) {
      STATUS_EL.textContent = 'online';
      window.location.replace(TARGET);
      return true;
    }
  } catch {
    /* sidecar still booting; ignore */
  }
  return false;
}

function statusFor(waitedMs) {
  const s = Math.floor(waitedMs / 1000);
  // До порога терпіння лічильника немає навмисно: цифра, що біжить із
  // першої секунди, перетворює звичайний старт на очікування з таймером.
  if (waitedMs < PATIENCE_MS) return 'гріюсь';
  if (waitedMs < GIVEN_UP_MS) {
    return `гріюсь ${s}s — довше, ніж звично; ядро ще піднімається`;
  }
  return `ядро не піднялося за ${s}s — чекаю далі, але щось не так`;
}

async function loop() {
  for (;;) {
    if (await pollOnce()) return;
    STATUS_EL.textContent = statusFor(performance.now() - t0);
    await new Promise((res) => setTimeout(res, POLL_MS));
  }
}

loop();
