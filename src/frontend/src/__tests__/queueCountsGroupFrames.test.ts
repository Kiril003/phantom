/**
 * Черга не применшує борг: групові кадри рахуються.
 *
 * Груповий лист лежить у черзі вузла ОКРЕМИМ рядком на кожного отримувача:
 * одне повідомлення на 31 людину — це 31 рядок. Вузол це знає й віддає двома
 * числами (`queued` і `group_frames_queued`), і в його ж коді написано, чому:
 * показати «1» означало б применшити борг.
 *
 * А клієнт типізував відповідь як `{ queued: number }` і друге число мовчки
 * викидав. Тобто людина бачила чергу меншою, ніж вона є, — і саме тоді, коли
 * різниця найбільша: у групі.
 *
 * П'ятий випадок того самого класу за добу: джерело каже правду, останній шар
 * бере з неї половину. Тому тест перевіряє САМЕ РЯДОК, який побачить людина.
 */
import { describe, expect, it } from 'vitest';

import { queueLabel } from '../utils/queueLabel';

describe('підпис черги', () => {
  it('групові кадри названі окремо — інакше борг применшено', () => {
    // Один лист у групу на 31 людину: вузол бачить 1 лист і 31 кадр.
    const text = queueLabel({ queued: 1, group_frames_queued: 31 });

    expect(text).toContain('31');
    expect(text).toContain('групових кадрів');
  });

  it('без групових кадрів підпис лишається як був', () => {
    expect(queueLabel({ queued: 4 })).toBe(' Разом у черзі: 4.');
    expect(queueLabel({ queued: 1 })).toBe('');
  });

  it('однина й множина не плутаються', () => {
    expect(queueLabel({ queued: 1, group_frames_queued: 1 })).toContain('1 груповий кадр');
    expect(queueLabel({ queued: 2, group_frames_queued: 5 })).toContain('2 листів');
  });

  it('немає відповіді вузла — немає й числа', () => {
    // Краще без числа, ніж із вигаданим нулем: нуль означав би «черга порожня».
    expect(queueLabel(null)).toBe('');
  });
});
