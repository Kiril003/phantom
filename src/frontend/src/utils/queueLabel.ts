/** Підпис черги вузла — те, що читає людина під застряглим листом.
 *
 *  Живе окремо від `ChatArea` навмисно. Перша версія тесту тримала **власну
 *  копію** цього правила, тобто перевіряла б себе саму: зміни в компоненті
 *  лишились би непоміченими. Це рівно та хвороба, яку ми весь день виполюємо
 *  в іншому коді — дві копії однієї угоди розходяться тихо.
 */
export interface QueueInfo {
  /** Скільки листів чекає. */
  queued: number;
  /** Скільки ОКРЕМИХ групових кадрів чекає.
   *
   *  Груповий лист лежить у черзі рядком на кожного отримувача: одне
   *  повідомлення на 31 людину — це 31 рядок. Вузол рахує їх окремо саме
   *  тому, що показати «1» означало б применшити борг. Клієнт це число
   *  викидав до 30.08.2026. */
  group_frames_queued?: number;
}

export function queueLabel(info: QueueInfo | null): string {
  if (!info) return '';
  const frames = info.group_frames_queued ?? 0;
  if (frames > 0) {
    return (
      ` Разом у черзі: ${info.queued} ${info.queued === 1 ? 'лист' : 'листів'}` +
      ` і ${frames} ${frames === 1 ? 'груповий кадр' : 'групових кадрів'}.`
    );
  }
  return info.queued > 1 ? ` Разом у черзі: ${info.queued}.` : '';
}
